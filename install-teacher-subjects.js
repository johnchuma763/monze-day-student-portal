const fs = require("fs");

const serverFile = "server-postgres.js";
const pageFile = "teacher-subjects.html";

let server = fs.readFileSync(serverFile, "utf8");

if (server.includes('app.get("/api/teacher/my-class-subjects"')) {
    console.log("Teacher subjects API already exists.");
} else {
    const marker = "/* ADMIN: CLASS SUBJECT MANAGEMENT */";

    if (!server.includes(marker)) {
        console.error("Could not find the class subjects API location.");
        process.exit(1);
    }

    const route = `
/* TEACHER: VIEW APPROVED SUBJECTS AND CLASS SUBJECT TABLES */
app.get("/api/teacher/my-class-subjects", async (req, res) => {
    if (!req.session.teacherId) {
        return res.status(401).json({ message: "Please log in first." });
    }

    try {
        const teacherResult = await pool.query(
            \`SELECT subjects, classes, approved
             FROM teachers
             WHERE id = $1\`,
            [req.session.teacherId]
        );

        const teacher = teacherResult.rows[0];

        if (!teacher) {
            return res.status(404).json({ message: "Teacher account not found." });
        }

        if (Number(teacher.approved) !== 1) {
            return res.status(403).json({
                message: "Your teacher account must be approved before viewing assignments."
            });
        }

        const assignedSubjects = (teacher.subjects || "")
            .split(",")
            .map(value => value.trim())
            .filter(Boolean);

        const assignedClasses = (teacher.classes || "")
            .split(",")
            .map(value => value.trim())
            .filter(Boolean);

        await pool.query(\`
            CREATE TABLE IF NOT EXISTS class_subjects (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                form_number INTEGER NOT NULL CHECK (form_number BETWEEN 1 AND 4),
                class_letter CHAR(1) NOT NULL CHECK (class_letter IN ('A','B','C','D')),
                subject_name TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE(form_number, class_letter, subject_name)
            )
        \`);

        const classes = [];

        for (const className of assignedClasses) {
            const match = className.match(/^Form\\s*([1-4])\\s*([A-D])$/i);

            if (!match) continue;

            const formNumber = Number(match[1]);
            const classLetter = match[2].toUpperCase();

            const subjectResult = await pool.query(
                \`SELECT id, subject_name
                 FROM class_subjects
                 WHERE form_number = $1
                   AND UPPER(TRIM(class_letter::text)) = $2
                 ORDER BY subject_name\`,
                [formNumber, classLetter]
            );

            classes.push({
                class_name: "Form " + formNumber + classLetter,
                subjects: subjectResult.rows.map(subject => ({
                    id: subject.id,
                    subject_name: subject.subject_name,
                    is_assigned: assignedSubjects.some(
                        assigned =>
                            assigned.trim().toLowerCase() ===
                            subject.subject_name.trim().toLowerCase()
                    )
                }))
            });
        }

        res.json({
            assigned_subjects: assignedSubjects,
            classes
        });

    } catch (error) {
        console.error("Teacher subjects error:", error);
        res.status(500).json({
            message: "Unable to load your subjects and classes."
        });
    }
});

`;

    server = server.replace(marker, route + marker);
    fs.writeFileSync(serverFile, server);
    console.log("Teacher subjects API installed.");
}

