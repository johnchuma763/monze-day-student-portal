app.post("/api/teacher/register", async (req, res) => {
    const {
        full_name, email, password, subjects,
        classes, is_class_teacher, assigned_class
    } = req.body;

    if (
        !full_name?.trim() ||
        !email?.trim() ||
        !password ||
        password.length < 8 ||
        !subjects?.trim() ||
        !classes?.trim() ||
        !["yes", "no"].includes(is_class_teacher)
    ) {
        return res.status(400).json({
            message: "Please complete all required fields."
        });
    }

    const normalizedAssignedClass = (assigned_class || "")
        .trim()
        .replace(/^Form\s*([1-4])\s*([A-D])$/i, "Form $1$2");

    if (
        is_class_teacher === "yes" &&
        !/^Form [1-4][A-D]$/.test(normalizedAssignedClass)
    ) {
        return res.status(400).json({
            message: "Please select one valid assigned class, such as Form 2C."
        });
    }

    try {
        const normalizedEmail = email.trim().toLowerCase();

        const existing = await pool.query(
            "SELECT id FROM teachers WHERE email = $1",
            [normalizedEmail]
        );

        if (existing.rows.length > 0) {
            return res.status(409).json({
                message: "An account with this email already exists."
            });
        }

        const hashedPassword = await bcrypt.hash(password, 12);

        await pool.query(`
            INSERT INTO teachers (
                full_name, email, password, subjects,
                classes, is_class_teacher, assigned_class, approved
            )
            VALUES ($1, $2, $3, $4, $5, $6, $7, 0)
        `, [
            full_name.trim(),
            normalizedEmail,
            hashedPassword,
            subjects.trim(),
            classes.trim(),
            is_class_teacher === "yes" ? 1 : 0,
            is_class_teacher === "yes" ? normalizedAssignedClass : ""
        ]);

        res.status(201).json({
            message: "Registration submitted! Please wait for administrator approval."
        });
    } catch (error) {
        console.error(error);

        if (error.code === "23505") {
            return res.status(409).json({
                message: "An account with this email already exists."
            });
        }

        res.status(500).json({
            message: "Unable to complete registration."
        });
    }
});

