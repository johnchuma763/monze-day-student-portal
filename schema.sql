-- MONZE DAY SECONDARY SCHOOL STUDENT PORTAL
-- PostgreSQL database schema for Neon

CREATE TABLE IF NOT EXISTS students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    student_number TEXT NOT NULL UNIQUE,
    class_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    must_change_password INTEGER NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS teachers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    subjects TEXT DEFAULT '',
    classes TEXT DEFAULT '',
    is_class_teacher INTEGER DEFAULT 0,
    assigned_class TEXT DEFAULT '',
    approved INTEGER NOT NULL DEFAULT 0,
    photo_url TEXT DEFAULT ''
);

CREATE TABLE IF NOT EXISTS admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name TEXT NOT NULL,
    email TEXT NOT NULL UNIQUE,
    password TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS announcements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    message TEXT NOT NULL,
    author_name TEXT NOT NULL,
    author_role TEXT NOT NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    is_published INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS academic_results (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    subject TEXT NOT NULL,
    term TEXT NOT NULL,
    year INTEGER NOT NULL,
    score REAL NOT NULL CHECK (score BETWEEN 0 AND 100),
    grade TEXT,
    remarks TEXT,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE,
    expires_at BIGINT NOT NULL,
    used INTEGER NOT NULL DEFAULT 0
);

-- Indexes for common lookups
CREATE INDEX IF NOT EXISTS idx_results_student_id
ON academic_results(student_id);

CREATE INDEX IF NOT EXISTS idx_reset_tokens_student_id
ON password_reset_tokens(student_id);

CREATE INDEX IF NOT EXISTS idx_students_email
ON students(email);

CREATE INDEX IF NOT EXISTS idx_teachers_email
ON teachers(email);
