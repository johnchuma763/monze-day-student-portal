const fs = require("fs");

const file = "server-postgres.js";
let source = fs.readFileSync(file, "utf8");

const marker = "// ADMINISTRATOR STUDENT MANAGEMENT";

if (source.includes("/api/admin/class-subjects")) {
    console.log("Subject API already exists.");
    process.exit(0);
}

if (!source.includes(marker)) {
    console.log("Insertion point not found.");
    process.exit(1);
}
const code = `
/* ADMIN: CLASS SUBJECT MANAGEMENT */

app.get("/api/admin/class-subjects", requireAdmin, async (req, res) => {
    try {
        const result = await pool.query(
            \`SELECT id, form_number, class_letter, subject_name
             FROM class_subjects
             ORDER BY form_number, class_letter, subject_name\`
        );

        res.json(result.rows);
    } catch (error) {
        console.error(error);
        res.status(500).json({ message: "Unable to load subjects." });
    }
});

app.post("/api/admin/class-subjects", requireAdmin, async (req, res) => {
    try {
        const form = Number(req.body.form_number);
        const letter = String(req.body.class_letter || "").toUpperCase();
        const subject = String(req.body.subject_name || "").trim();

        if (
            !Number.isInteger(form) || form < 1 || form > 4 ||
            !["A", "B", "C", "D"].includes(letter) ||
            !subject || subject.length > 100
        ) {
            return res.status(400).json({
                message: "Enter a valid form, class and subject."
            });
        }

        await pool.query(\`
            CREATE TABLE IF NOT EXISTS class_subjects (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                form_number INTEGER NOT NULL CHECK (form_number BETWEEN 1 AND 4),
                class_letter CHAR(1) NOT NULL CHECK (class_letter IN ('A','B','C','D')),
                subject_name TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE (form_number, class_letter, subject_name)
            )
        \`);

        const result = await pool.query(
            \`INSERT INTO class_subjects
             (form_number, class_letter, subject_name)
             VALUES ($1, $2, $3)
             ON CONFLICT (form_number, class_letter, subject_name)
             DO NOTHING
             RETURNING *\`,
            [form, letter, subject]
        );

        if (!result.rows[0]) {
            return res.status(409).json({
                message: "This subject already exists."
            });
        }

        res.status(201).json({
            message: "Subject added successfully.",
            subject: result.rows[0]
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({ message: "Unable to add subject." });
    }
});
`;
const extra = `

app.patch("/api/admin/class-subjects/:id", requireAdmin, async (req, res) => {
    try {
        const subject = String(req.body.subject_name || "").trim();

        if (!subject || subject.length > 100) {
            return res.status(400).json({ message: "Invalid subject name." });
        }

        const result = await pool.query(
            "UPDATE class_subjects SET subject_name = $1 WHERE id = $2 RETURNING *",
            [subject, req.params.id]
        );

        if (!result.rows[0]) {
            return res.status(404).json({ message: "Subject not found." });
        }

        res.json({ message: "Subject updated successfully." });
    } catch (error) {
        console.error(error);
        res.status(500).json({ message: "Unable to update subject." });
    }
});

app.delete("/api/admin/class-subjects/:id", requireAdmin, async (req, res) => {
    try {
        const result = await pool.query(
            "DELETE FROM class_subjects WHERE id = $1 RETURNING id",
            [req.params.id]
        );

        if (!result.rows[0]) {
            return res.status(404).json({ message: "Subject not found." });
        }

        res.json({ message: "Subject deleted successfully." });
    } catch (error) {
        console.error(error);
        res.status(500).json({ message: "Unable to delete subject." });
    }
});

`;

source = source.replace(marker, code + extra + "\n" + marker);
fs.writeFileSync(file, source);

console.log("Subject management API installed successfully.");

