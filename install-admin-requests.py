routes = '''
// ADMINISTRATOR ACCOUNT REQUESTS

app.post("/api/admin-requests", async (req, res) => {
    try {
        await adminRequestsReady;

        const fullName = String(req.body.fullName || "").trim();
        const email = String(req.body.email || "").trim().toLowerCase();
        const reason = String(req.body.reason || "").trim();

        if (!fullName || !email || !reason) {
            return res.status(400).json({
                message: "Please complete all fields."
            });
        }

        if (fullName.length > 150 || email.length > 254 || reason.length > 1000) {
            return res.status(400).json({
                message: "One or more fields are too long."
            });
        }

        if (!/^[^\\s@]+@[^\\s@]+\\.[^\\s@]+$/.test(email)) {
            return res.status(400).json({
                message: "Enter a valid email address."
            });
        }

        await pool.query(
            `INSERT INTO admin_account_requests
             (full_name, email, reason)
             VALUES ($1, $2, $3)`,
            [fullName, email, reason]
        );

        res.status(201).json({
            message: "Your request has been submitted for review."
        });
    } catch (error) {
        console.error("Administrator request error:", error);
        res.status(500).json({
            message: "Unable to submit your request."
        });
    }
});

app.get("/api/admin-requests", requireAdmin, async (req, res) => {
    try {
        await adminRequestsReady;
        const result = await pool.query(
            `SELECT id, full_name, email, reason, status, created_at
             FROM admin_account_requests
             ORDER BY created_at DESC`
        );
        res.json(result.rows);
    } catch (error) {
        console.error(error);
        res.status(500).json({
            message: "Unable to load administrator requests."
        });
    }
});

app.patch("/api/admin-requests/:id", requireAdmin, async (req, res) => {
    try {
        await adminRequestsReady;

        const id = Number(req.params.id);
        const status = String(req.body.status || "");

        if (!Number.isSafeInteger(id) || id < 1 ||
            !["approved", "rejected"].includes(status)) {
            return res.status(400).json({
                message: "Invalid request or status."
            });
        }

        const result = await pool.query(
            `UPDATE admin_account_requests
             SET status = $1
             WHERE id = $2 AND status = 'pending'
             RETURNING id`,
            [status, id]
        );

        if (!result.rows.length) {
            return res.status(404).json({
                message: "Pending request not found."
            });
        }

        res.json({
            message: "Request " + status + ". An administrator account has not been created."
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({
            message: "Unable to update the request."
        });
    }
});

'''

