require("dotenv").config();
const { Pool } = require("pg");

const pool = new Pool({
  connectionString: process.env.DATABASE_URL,
  ssl: { rejectUnauthorized: false }
});

async function migrate() {
  try {
    await pool.query(`
      CREATE TABLE IF NOT EXISTS library_resources (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        teacher_id BIGINT REFERENCES teachers(id) ON DELETE SET NULL,
        title TEXT NOT NULL,
        description TEXT,
        class_name TEXT NOT NULL,
        subject_name TEXT NOT NULL,
        category TEXT NOT NULL DEFAULT 'notes'
          CHECK (category IN ('notes', 'revision', 'past_paper', 'textbook', 'other')),
        file_name TEXT NOT NULL UNIQUE,
        original_file_name TEXT NOT NULL,
        mime_type TEXT NOT NULL,
        file_size BIGINT NOT NULL,
        created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
      );

      CREATE INDEX IF NOT EXISTS idx_library_class
        ON library_resources(class_name);

      CREATE INDEX IF NOT EXISTS idx_library_subject
        ON library_resources(subject_name);

      CREATE INDEX IF NOT EXISTS idx_library_teacher
        ON library_resources(teacher_id);

      CREATE INDEX IF NOT EXISTS idx_library_created
        ON library_resources(created_at);
    `);

    console.log("SUCCESS: Digital Library database created.");
  } catch (error) {
    console.error("Library migration failed:", error.message);
    process.exitCode = 1;
  } finally {
    await pool.end();
  }
}

migrate();
