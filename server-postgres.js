/* STUDENT: VIEW ASSIGNED SUBJECTS */
app.get("/api/student/subjects", async (req, res) => {
    if (!req.session.studentId) {
        return res.status(401).json({
            message: "Please sign in first."
        });
    }

    try {
        const studentResult = await pool.query(
            `SELECT id, class_name, must_change_password
             FROM students
             WHERE id = $1`,
            [req.session.studentId]
        );

        const student = studentResult.rows[0];

        if (!student) {
            return res.status(404).json({
                message: "Student account not found."
            });
        }

        if (Number(student.must_change_password) === 1) {
            return res.status(403).json({
                mustChangePassword: true,
                message: "Please change your temporary password first."
            });
        }

        const normalizeClass = value =>
            String(value || "").trim().replace(/\s+/g, "").toLowerCase();

        const studentClass = normalizeClass(student.class_name);

        if (!studentClass) {
            return res.json({ subjects: [] });
        }

        const teacherResult = await pool.query(
            `SELECT full_name, subjects, classes,
                    is_class_teacher, assigned_class
             FROM teachers
             WHERE approved = 1`
        );

        const subjectMap = new Map();

        for (const teacher of teacherResult.rows) {
            const assignedClasses = String(teacher.classes || "")
                .split(",")
                .map(normalizeClass)
                .filter(Boolean);

            if (
                Number(teacher.is_class_teacher) === 1 ||
                teacher.is_class_teacher === true ||
                teacher.is_class_teacher === "t"
            ) {
                if (teacher.assigned_class) {
                    assignedClasses.push(
                        normalizeClass(teacher.assigned_class)
                    );
                }
            }

            if (!assignedClasses.includes(studentClass)) {
                continue;
            }

            const subjects = String(teacher.subjects || "")
                .split(",")
                .map(value => value.trim())
                .filter(Boolean);

            for (const subject of subjects) {
                const key = subject.toLowerCase();

                if (!subjectMap.has(key)) {
                    subjectMap.set(key, {
                        name: subject,
                        teachers: []
                    });
                }

                const entry = subjectMap.get(key);

                if (!entry.teachers.includes(teacher.full_name)) {
                    entry.teachers.push(teacher.full_name);
                }
            }
        }

        const subjects = [...subjectMap.values()]
            .sort((a, b) => a.name.localeCompare(b.name));

        res.json({ subjects });

    } catch (error) {
        console.error("Student subjects error:", error);

        res.status(500).json({
            message: "Unable to load your subjects."
        });
    }
});

