    const route = `
/* ADMIN: SAVE A COMPLETE CLASS SUBJECT LIST */
app.post("/api/admin/class-subjects/batch", requireAdmin, async (req, res) => {
    const form = Number(req.body.form_number);
    const letter = String(req.body.class_letter || "").toUpperCase();
    const subjects = req.body.subjects;

    if (
        !Number.isInteger(form) || form < 1 || form > 4 ||
        !["A", "B", "C", "D"].includes(letter) ||
        !Array.isArray(subjects) || subjects.length === 0
    ) {
        return res.status(400).json({
            message: "Select a valid class and enter at least one subject."
        });
    }

    const cleanSubjects = subjects.map(s => String(s).trim());

    if (
        cleanSubjects.some(s => !s || s.length > 100) ||
        new Set(cleanSubjects.map(s => s.toLowerCase())).size !== cleanSubjects.length
    ) {
        return res.status(400).json({
            message: "Remove empty or duplicate subjects from your list."
        });
    }

    const client = await pool.connect();

    try {
        await client.query("BEGIN");

        await client.query(\`
            CREATE TABLE IF NOT EXISTS class_subjects (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                form_number INTEGER NOT NULL CHECK (form_number BETWEEN 1 AND 4),
                class_letter CHAR(1) NOT NULL CHECK (class_letter IN ('A','B','C','D')),
                subject_name TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE(form_number, class_letter, subject_name)
            )
        \`);

        const existing = await client.query(
            \`SELECT subject_name FROM class_subjects
             WHERE form_number = $1 AND class_letter = $2\`,
            [form, letter]
        );

        const existingNames = new Set(
            existing.rows.map(row => row.subject_name.toLowerCase())
        );

        const duplicates = cleanSubjects.filter(
            name => existingNames.has(name.toLowerCase())
        );

        if (duplicates.length) {
            await client.query("ROLLBACK");
            return res.status(409).json({
                message: "Already registered for this class: " + duplicates.join(", ")
            });
        }

        for (const subject of cleanSubjects) {
            await client.query(
                \`INSERT INTO class_subjects
                 (form_number, class_letter, subject_name)
                 VALUES ($1, $2, $3)\`,
                [form, letter, subject]
            );
        }

        await client.query("COMMIT");

        res.status(201).json({
            message: cleanSubjects.length + " subjects saved successfully for Form " + form + letter + "."
        });
    } catch (error) {
        await client.query("ROLLBACK");
        console.error(error);
        res.status(500).json({ message: "Unable to save the class subjects." });
    } finally {
        client.release();
    }
});

`;

    server = server.replace(marker, route + marker);
    fs.writeFileSync(serverFile, server);
