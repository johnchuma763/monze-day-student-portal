app.post("/api/student/change-password", async (req, res) => {
    try {
        if (!req.session.studentId) {
            return res.status(401).json({
                message: "Please sign in first."
            });
        }

        const { currentPassword, newPassword } = req.body;

        if (!currentPassword || !newPassword) {
            return res.status(400).json({
                message: "Complete all password fields."
            });
        }

        if (newPassword.length < 8) {
            return res.status(400).json({
                message: "Your new password must contain at least 8 characters."
            });
        }

        if (currentPassword === newPassword) {
            return res.status(400).json({
                message: "Choose a different new password."
            });
        }

        const result = await pool.query(
            "SELECT password FROM students WHERE id = $1",
            [req.session.studentId]
        );

        const student = result.rows[0];

        if (!student) {
            return res.status(404).json({
                message: "Student account not found."
            });
        }

        const matches = await bcrypt.compare(
            currentPassword,
            student.password
        );

        if (!matches) {
            return res.status(401).json({
                message: "Current password is incorrect."
            });
        }

        const hashedPassword = await bcrypt.hash(newPassword, 12);

        await pool.query(`
            UPDATE students
            SET password = $1, must_change_password = 0
            WHERE id = $2
        `, [hashedPassword, req.session.studentId]);

        res.json({
            message: "Password changed successfully. You can now access your dashboard."
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({
            message: "Unable to change password."
        });
    }
});

const resetLimiter = new Map();

// Request a password-reset link
app.post("/api/student/forgot-password", async (req, res) => {
    try {
        const email = String(req.body.email || "").trim().toLowerCase();

        if (!email || email.length > 254) {
            return res.status(400).json({
                message: "Enter a valid email address."
            });
        }

        const now = Date.now();
        const previous = resetLimiter.get(email) || 0;

        if (now - previous < 60000) {
            return res.json({
                message: "If an account exists, reset instructions will be provided."
            });
        }

        resetLimiter.set(email, now);

        const result = await pool.query(
            "SELECT id FROM students WHERE email = $1",
            [email]
        );

        const student = result.rows[0];

        if (student) {
            const token = crypto.randomBytes(32).toString("hex");
            const tokenHash = crypto.createHash("sha256")
                .update(token).digest("hex");

            const client = await pool.connect();

            try {
                await client.query("BEGIN");

                await client.query(
                    "DELETE FROM password_reset_tokens WHERE student_id = $1",
                    [student.id]
                );

                await client.query(`
                    INSERT INTO password_reset_tokens
                    (student_id, token_hash, expires_at)
                    VALUES ($1, $2, $3)
                `, [student.id, tokenHash, now + 15 * 60 * 1000]);

                await client.query("COMMIT");
            } catch (error) {
                await client.query("ROLLBACK");
                throw error;
            } finally {
                client.release();
            }

            if (process.env.NODE_ENV !== "production") {
                const link = "http://" + req.get("host") +
                    "/reset-password.html?token=" + token;

                console.log("DEVELOPMENT PASSWORD RESET LINK:", link);
            }
        }

        res.json({
            message: "If an account exists, reset instructions will be provided."
        });
    } catch (error) {
        console.error(error);
        res.status(500).json({
            message: "Unable to process your request."
        });
    }
});

// Complete a password reset
app.post("/api/student/reset-password", async (req, res) => {
    const client = await pool.connect();

    try {
        const token = String(req.body.token || "");
        const newPassword = String(req.body.newPassword || "");

        if (!token || token.length !== 64 || !/^[a-f0-9]+$/i.test(token)) {
            return res.status(400).json({
                message: "Invalid or expired reset link."
            });
        }

        if (newPassword.length < 8 || newPassword.length > 128) {
            return res.status(400).json({
                message: "Password must contain between 8 and 128 characters."
            });
        }

        const tokenHash = crypto.createHash("sha256")
            .update(token).digest("hex");

        await client.query("BEGIN");

        const result = await client.query(`
            SELECT id, student_id
            FROM password_reset_tokens
            WHERE token_hash = $1
              AND used = 0
              AND expires_at > $2
            FOR UPDATE
        `, [tokenHash, Date.now()]);

        const record = result.rows[0];

        if (!record) {
            await client.query("ROLLBACK");
            return res.status(400).json({
                message: "Invalid or expired reset link."
            });
        }

        const hashedPassword = await bcrypt.hash(newPassword, 12);

        await client.query(`
            UPDATE students
            SET password = $1, must_change_password = 0
            WHERE id = $2
        `, [hashedPassword, record.student_id]);

        await client.query(
            "UPDATE password_reset_tokens SET used = 1 WHERE id = $1",
            [record.id]
        );

        await client.query(`
            DELETE FROM password_reset_tokens
            WHERE student_id = $1 AND id != $2
        `, [record.student_id, record.id]);

        await client.query("COMMIT");

        res.json({
            message: "Password reset successfully. You can now sign in."
        });
    } catch (error) {
        await client.query("ROLLBACK").catch(() => {});
        console.error(error);
        res.status(500).json({
            message: "Unable to reset your password."
        });
    } finally {
        client.release();
    }
});

