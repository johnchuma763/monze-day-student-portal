require("dotenv").config();

const { Pool } = require("pg");

const pool = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: { rejectUnauthorized: false }
});

async function migrate() {
    try {
        await pool.query(`
            CREATE TABLE IF NOT EXISTS assignments (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                teacher_id BIGINT NOT NULL REFERENCES teachers(id) ON DELETE CASCADE,
                title TEXT NOT NULL,
                instructions TEXT NOT NULL,
                class_name TEXT NOT NULL,
                subject_name TEXT NOT NULL,
                due_at TIMESTAMPTZ NOT NULL,
                status TEXT NOT NULL DEFAULT 'published'
                    CHECK (status IN ('draft', 'published', 'closed')),
                attachment_name TEXT,
                attachment_original_name TEXT,
                attachment_mime_type TEXT,
                attachment_size BIGINT,
                created_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP
            );

            CREATE TABLE IF NOT EXISTS assignment_submissions (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                assignment_id BIGINT NOT NULL REFERENCES assignments(id) ON DELETE CASCADE,
                student_id BIGINT NOT NULL REFERENCES students(id) ON DELETE CASCADE,
                file_name TEXT NOT NULL,
                original_file_name TEXT NOT NULL,
                mime_type TEXT NOT NULL,
                file_size BIGINT NOT NULL,
                submitted_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                status TEXT NOT NULL DEFAULT 'submitted'
                    CHECK (status IN ('submitted', 'graded')),
                UNIQUE (assignment_id, student_id)
            );

            CREATE TABLE IF NOT EXISTS assignment_feedback (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                submission_id BIGINT NOT NULL UNIQUE
                    REFERENCES assignment_submissions(id) ON DELETE CASCADE,
                teacher_id BIGINT NOT NULL REFERENCES teachers(id) ON DELETE CASCADE,
                marks NUMERIC(6,2),
                maximum_marks NUMERIC(6,2),
                comments TEXT,
                graded_at TIMESTAMPTZ DEFAULT CURRENT_TIMESTAMP,
                CHECK (
                    (marks IS NULL AND maximum_marks IS NULL)
                    OR
                    (marks IS NOT NULL AND maximum_marks IS NOT NULL
                     AND marks >= 0 AND maximum_marks > 0
                     AND marks <= maximum_marks)
                )
            );

            CREATE INDEX IF NOT EXISTS idx_assignments_teacher
            ON assignments(teacher_id);

            CREATE INDEX IF NOT EXISTS idx_assignments_class
            ON assignments(class_name);

            CREATE INDEX IF NOT EXISTS idx_assignments_due
            ON assignments(due_at);

            CREATE INDEX IF NOT EXISTS idx_submissions_student
            ON assignment_submissions(student_id);

            CREATE INDEX IF NOT EXISTS idx_submissions_assignment
            ON assignment_submissions(assignment_id);
        `);

        console.log("SUCCESS: Assignment database created.");

    } catch (error) {
        console.error("Migration failed:", error.message);
        process.exitCode = 1;
    } finally {
        await pool.end();
    }
}

migrate();
