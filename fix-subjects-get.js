const fs = require("fs");
const file = "server-postgres.js";
let source = fs.readFileSync(file, "utf8");

const start = source.indexOf('app.get("/api/admin/class-subjects"');
const end = source.indexOf('app.post("/api/admin/class-subjects"', start);

if (start < 0 || end < 0) {
    console.log("Could not locate both subject routes.");
    process.exit(1);
}

let route = source.slice(start, end);

if (!route.includes("CREATE TABLE IF NOT EXISTS class_subjects")) {
    const point = route.indexOf("    try {") + "    try {".length;

    const setup = `
        await pool.query(\`
            CREATE TABLE IF NOT EXISTS class_subjects (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                form_number INTEGER NOT NULL CHECK (form_number BETWEEN 1 AND 4),
                class_letter CHAR(1) NOT NULL CHECK (class_letter IN ('A','B','C','D')),
                subject_name TEXT NOT NULL,
                created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                UNIQUE(form_number, class_letter, subject_name)
            )
        \`);
`;
    route = route.slice(0, point) + setup + route.slice(point);
    source = source.slice(0, start) + route + source.slice(end);
    fs.writeFileSync(file, source);
    console.log("GET route corrected successfully.");
} else {
    console.log("GET route already creates the table.");
}
